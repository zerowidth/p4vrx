"""Bake fonts and icons into 4-bit alpha bitmaps for the P4. Run with rake ui:fonts, or uv run --with freetype-py.
  bake.py FONT OUT.c NAME:SIZE[:CHARS] ...
    Printable ASCII, or only CHARS (the rest are empty); digits use the font's tabular forms (glyph names ending
    .tf) when it has them.
  bake.py icons FA_DIR OUT.c ICONS NAME:SIZE ...
    Font Awesome icons by name from FA_DIR (the desktop release), comma-separated, "brands/" before a brand's
    name; OUT.h gets an enum of them. Each icon sits centred in a cell of the set's widest advance and the
    font's full height, so icons drawn at one origin line up as Font Awesome's layers do.
  bake.py badge FA_DIR OUT.c NAME ICON SIZE HALO
    One Font Awesome icon as two 8-bit alpha maps for drawing over video: its fill, and a dark halo HALO px
    wide, dilated then blurred. Needs numpy."""
import json
import pathlib
import sys

import freetype


def glyph_index(face, ch):
    if ch.isdigit():
        tf = face.get_name_index(f"{['zero','one','two','three','four','five','six','seven','eight','nine'][int(ch)]}.tf".encode())
        if tf:
            return tf
    return face.get_char_index(ord(ch))


def bake(face, name, size, chars=None):
    face.set_pixel_sizes(0, size)
    glyphs, data = [], bytearray()
    for code in range(32, 127):
        if chars and chr(code) not in chars:
            glyphs.append((0, 0, 0, 0, 0, 0))
            continue
        face.load_glyph(glyph_index(face, chr(code)), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        offset = len(data)
        for y in range(h):
            row = bm.buffer[y * bm.pitch:y * bm.pitch + w] + [0]
            for x in range(0, w, 2):
                data.append((row[x] >> 4) << 4 | (row[x + 1] >> 4))
        glyphs.append((offset, w, h, g.bitmap_left, g.bitmap_top, (g.advance.x + 32) >> 6))
    m = face.size
    lines = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const font_glyph_t {name}_glyphs[] = {{")
    for code, (o, w, h, l, t, a) in zip(range(32, 127), glyphs):
        lines.append(f"    {{{o}, {w}, {h}, {l}, {t}, {a}}}, /* {chr(code)!r} */")
    lines.append("};")
    lines.append(f"const font_t {name} = {{{name}_glyphs, {name}_bits, {m.ascender >> 6}, {-(m.descender >> 6)}}};")
    return "\n".join(lines)


def pack(bm, data):
    offset = len(data)
    for y in range(bm.rows):
        row = bm.buffer[y * bm.pitch:y * bm.pitch + bm.width] + [0]
        for x in range(0, bm.width, 2):
            data.append((row[x] >> 4) << 4 | (row[x + 1] >> 4))
    return offset


def bake_icons(fa, icons, name, size):
    faces = {style: freetype.Face(str(next((fa / "otfs").glob(f"*{file}*.otf")))) for style, file in
             (("solid", "Free-Solid"), ("brands", "Brands"))}
    meta = json.loads((fa / "metadata" / "icons.json").read_text())
    rendered = []
    for icon in icons:
        style, _, key = icon.rpartition("/")
        face = faces[style or "solid"]
        face.set_pixel_sizes(0, size)
        face.load_char(int(meta[key]["unicode"], 16), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
        g, bm = face.glyph, face.glyph.bitmap
        # The glyph slot is reused by the next load, so take a copy of the bitmap now.
        copy = type("Bitmap", (), {"width": bm.width, "rows": bm.rows, "pitch": bm.pitch, "buffer": list(bm.buffer)})
        rendered.append((copy, g.bitmap_left, g.bitmap_top, (g.advance.x + 32) >> 6, face.size.ascender >> 6))
    cell_w = max(r[3] for r in rendered)
    lines, data = [f"static const font_glyph_t {name}_glyphs[] = {{"], bytearray()
    for icon, (bm, left, top, advance, ascent) in zip(icons, rendered):
        offset = pack(bm, data)
        lines.append(f"    {{{offset}, {bm.width}, {bm.rows}, {(cell_w - advance) // 2 + left}, {ascent - top}, {advance}}}, /* {icon} */")
    lines.append("};")
    bits = [f"static const uint8_t {name}_bits[] = {{"]
    for i in range(0, len(data), 24):
        bits.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    bits.append("};")
    return "\n".join(bits + lines + [f"const icon_set_t {name} = {{{name}_glyphs, {name}_bits, {cell_w}, {size}}};"])


def icons_main(fa, out, icons, specs):
    fa, icons = pathlib.Path(fa), icons.split(",")
    version = fa.name.removeprefix("fontawesome-free-").removesuffix("-desktop")
    note = (f"/* Generated by ui/fonts/bake.py from Font Awesome Free {version}: icons under CC BY 4.0, fonts under the "
            "SIL Open Font License 1.1 (ui/fonts/LICENSE-FontAwesome.txt). */")
    parts = [note, '#include "icons.h"', ""]
    for spec in specs:
        name, size = spec.split(":")
        parts += [bake_icons(fa, icons, name, int(size)), ""]
    pathlib.Path(out).write_text("\n".join(parts))
    enum = ", ".join("ICON_" + i.rpartition("/")[2].upper().replace("-", "_") for i in icons)
    header = [note, "#pragma once", "", '#include "font.h"', "", f"typedef enum {{ {enum} }} icon_t;", ""]
    header += [f"extern const icon_set_t {spec.split(':')[0]};" for spec in specs] + [""]
    pathlib.Path(out).with_suffix(".h").write_text("\n".join(header))


def bake_badge(fa, out, name, icon, size, halo):
    import numpy as np
    fa = pathlib.Path(fa)
    face = freetype.Face(str(next((fa / "otfs").glob("*Free-Solid*.otf"))))
    meta = json.loads((fa / "metadata" / "icons.json").read_text())
    face.set_pixel_sizes(0, size)
    face.load_char(int(meta[icon]["unicode"], 16), freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_LIGHT)
    bm = face.glyph.bitmap
    glyph = np.array(bm.buffer, dtype=np.float64).reshape(bm.rows, bm.pitch)[:, :bm.width] / 255
    pad = 2 * halo
    fill = np.pad(glyph, pad)
    # The halo: the fill grown by `halo` px in every direction, then softened by a Gaussian of a third of that.
    r = np.arange(-halo, halo + 1)
    disk = (r[:, None] ** 2 + r[None, :] ** 2) <= halo * halo
    grown = np.zeros_like(fill)
    for dy, dx in zip(*np.nonzero(disk)):
        grown = np.maximum(grown, np.roll(np.roll(fill, dy - halo, 0), dx - halo, 1))
    sigma = halo / 3
    k = np.exp(-0.5 * (np.arange(-3 * halo, 3 * halo + 1) / sigma) ** 2)
    k /= k.sum()
    blurred = np.apply_along_axis(lambda v: np.convolve(v, k, "same"), 0, grown)
    blurred = np.apply_along_axis(lambda v: np.convolve(v, k, "same"), 1, blurred)
    h, w = fill.shape
    version = fa.name.removeprefix("fontawesome-free-").removesuffix("-desktop")
    lines = [f"/* Generated by ui/fonts/bake.py from Font Awesome Free {version} ({icon}, solid, {size} px, halo {halo} px): "
             "icons under CC BY 4.0 (ui/fonts/LICENSE-FontAwesome.txt). */", '#include "font.h"', ""]
    for part, a in (("fill", fill), ("halo", np.clip(blurred, 0, 1))):
        data = np.round(a * 255).astype(np.uint8).ravel()
        lines.append(f"static const uint8_t {name}_{part}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ", ".join(f"{b}" for b in data[i:i + 24]) + ",")
        lines.append("};")
    lines.append(f"const overlay_t {name} = {{{w}, {h}, {name}_fill, {name}_halo}};")
    pathlib.Path(out).write_text("\n".join(lines) + "\n")


def main():
    if sys.argv[1] == "badge":
        bake_badge(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], int(sys.argv[6]), int(sys.argv[7]))
        return
    if sys.argv[1] == "icons":
        icons_main(sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5:])
        return
    font, out, specs = sys.argv[1], sys.argv[2], sys.argv[3:]
    face = freetype.Face(font)
    parts = [f"/* Generated by ui/fonts/bake.py from {face.family_name.decode()} {face.style_name.decode()}; "
             "the font is under the SIL Open Font License 1.1 (ui/fonts/OFL-Inter.txt). */",
             '#include "font.h"', ""]
    for spec in specs:
        name, size, *chars = spec.split(":", 2)
        parts.append(bake(face, name, int(size), chars[0] if chars else None))
        parts.append("")
    open(out, "w").write("\n".join(parts))


if __name__ == "__main__":
    main()
